function box(title, children, shade = SHADE) {
  return new Table({
    width: { size: 8600, type: WidthType.DXA },
    rows: [
      new TableRow({ children: [cell([pr([run(title, { bold: true, color: COLOR, size: SZ.SUB })], { after: 20 })], { w: 8600, shade })] }),
      new TableRow({ children: [cell(children, { w: 8600 })] }),
    ],
  });
}
const corrige = (txt) => pr([
  run("Corrigé : ", { bold: true, italic: true, color: C.GRAY, size: 22 }),
  run(txt, { italic: true, color: C.GRAY, size: 22 })], { after: 100 });
const exo = (titre, consigne) => pr([
  run(titre + "  ", { bold: true, color: COLOR }),
  run(consigne, { italic: true })], { after: 40 });
const item = (t) => p(t, { after: 20 });

