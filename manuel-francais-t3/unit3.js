const relier = (left, right) => new Table({
  width: { size: 8200, type: WidthType.DXA },
  rows: [
    new TableRow({ children: [
      cell([pr([run("Colonne A", { bold: true, size: 24, color: C.GRAY })], { after: 10 })], { w: 4100, shade: "F5F5F5" }),
      cell([pr([run("Colonne B", { bold: true, size: 24, color: C.GRAY })], { after: 10 })], { w: 4100, shade: "F5F5F5" }),
    ] }),
    ...left.map((l, i) => new TableRow({ children: [
      cell([pr([run("•  " + l)], { after: 10 })], { w: 4100 }),
      cell([pr([run("•  " + right[i])], { after: 10 })], { w: 4100 }),
    ] })),
  ],
});

const COLOR = "2471A3"; // bleu du temps qui passe
const SHADE = "D4E6F1";
const TOTAL = 72;
const META = (title, slo, session, materials) => ({
  theme: "UNITÉ 3 — LE TEMPS", title, slo,
  values: "autonomie, sens de la responsabilité", session, materials,
});

const bullet = (runs, o = {}) => pr(
  [run("•  ", { bold: true, color: COLOR, size: SZ.BODY }), ...runs],
  { after: 40, ...o });
const mot = (word, expl) => bullet([
  run(word, { bold: true, color: C.BLUE }), run("  =  "), run(expl)]);
function box(title, children, shade = SHADE) {
  return new Table({
    width: { size: 8600, type: WidthType.DXA },
    rows: [
      new TableRow({ children: [cell([pr([run(title, { bold: true, color: COLOR, size: SZ.SUB })], { after: 20 })], { w: 8600, shade })] }),
      new TableRow({ children: [cell(children, { w: 8600 })] }),
    ],
  });
}
const corrige = (txt) => pr([
  run("Corrigé : ", { bold: true, italic: true, color: C.GRAY, size: 22 }),
  run(txt, { italic: true, color: C.GRAY, size: 22 })], { after: 100 });
const exo = (titre, consigne) => pr([
  run(titre + "  ", { bold: true, color: COLOR }),
  run(consigne, { italic: true })], { after: 40 });
const item = (t) => p(t, { after: 20 });

