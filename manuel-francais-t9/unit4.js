const bullet = (runs, o = {}) => pr(
  [run("•  ", { bold: true, color: COLOR, size: SZ.BODY }), ...runs],
  { after: o.after != null ? o.after : 50 });
const mot = (word, expl) => bullet([
  run(word, { bold: true, color: C.SALMON, hl: true }), ...(expl ? [run("  —  " + expl)] : [])]);
const exLine = (runs, note, o = {}) => pr([
  run("–  ", { bold: true, color: COLOR }), ...runs.flat(),
  ...(note ? [run("   [" + note + "]", { italic: true, color: C.GRAY, size: 26 })] : []),
], { after: o.after != null ? o.after : 60 });
const relier = (left, right) => new Table({
  width: { size: 8200, type: WidthType.DXA },
  rows: [
    new TableRow({ children: [
      cell([pr([run("Colonne A", { bold: true, size: 24, color: C.GRAY })], { after: 10 })], { w: 4100, shade: "F5F5F5" }),
      cell([pr([run("Colonne B", { bold: true, size: 24, color: C.GRAY })], { after: 10 })], { w: 4100, shade: "F5F5F5" }),
    ] }),
    ...left.map((l, i) => new TableRow({ children: [
      cell([pr([run("•  " + l)], { after: 10 })], { w: 4100 }),
      cell([pr([run("•  " + right[i])], { after: 10 })], { w: 4100 }),
    ] })),
  ],
});
function box(title, children, shade = SHADE) {
  return new Table({
    width: { size: 10400, type: WidthType.DXA },
    rows: [
      new TableRow({ children: [cell(
        [p([run(title, { bold: true, color: COLOR, size: SZ.BODY })], { center: true, after: 40 })],
        { shade })] }),
      new TableRow({ children: [cell(children)] }),
    ],
  });
}
const corrige = (txt) => pr([run("Corrigé : ", { bold: true, italic: true, color: C.GRAY, size: 24 }),
  run(txt, { italic: true, color: C.GRAY, size: 24 })], { after: 90 });
const exNum = (titre, consigne) => pr([run(titre, { bold: true, color: C.SALMON }),
  ...(consigne ? [run(" " + consigne)] : [])], { after: 30 });
const item = (txt) => p(txt, { after: 20 });

